"""Удаление служебных надписей справочных правовых систем из извлечённого текста.

Удаляются только надписи, которые не являются текстом нормы: плашки
«Документ предоставлен КонсультантПлюс», «Дата сохранения», адреса сайтов
систем, колонтитулы «Страница N из M», примечания редакции системы
(«КонсультантПлюс: примечание.», «ГАРАНТ:», «Информация об изменениях»)
и водяные строки сайтов-распространителей. Отметки об изменениях
«(в ред. ...)», «(абзац введен ...)» и списки изменяющих документов
сохраняются: они относятся к истории редакции акта.
Исходные файлы пользователя этим модулем не изменяются.
"""
import re

_FLAGS = re.IGNORECASE | re.UNICODE

# Фразы, которые удаляются в любом месте строки.
INLINE_PATTERNS = [re.compile(p, _FLAGS) for p in (
    r'Документ\s+предоставлен\s*КонсультантПлюс',
    r'КонсультантПлюс\s*[-–—]?\s*надежная\s+правовая\s+(?:поддержка|система)',
    r'(?:https?://)?(?:www\.|login\.)?consultant\.ru(?:/\S*)?',
    r'Дата\s+сохранения:\s*\d{1,2}\.\d{1,2}\.\d{4}',
    r'Документ\s+предоставлен\s*(?:системой\s+)?ГАРАНТ\S*',
    r'(?:https?://)?(?:www\.|base\.|ivo\.|internet\.)?garant\.ru(?:/\S*)?',
    r'(?:https?://)?docs\.cntd\.ru(?:/\S*)?',
    r'(?:https?://)?(?:www\.)?(?:kodeks|techexpert)\.ru(?:/\S*)?',
    r'Локализация:\s*промышленная\s+безопасность\s+на\s+блог-инженера\.рф',
    r'(?:https?://)?(?:www\.)?(?:блог-инженера\.рф|xn--\-[0-9a-z-]*\.xn--p1ai)(?:/\S*)?',
)]

# Строки, которые целиком являются служебными (после удаления фраз выше).
LINE_PATTERNS = [re.compile(p, _FLAGS) for p in (
    r'^Страница\s+\d+\s+из\s+\d+$',
    r'^КонсультантПлюс$',
    r'^надежная\s+правовая\s+поддержка$',
    r'^(?:Система\s+)?ГАРАНТ(?:\.РУ)?$',
    r'^Информационно-правовое\s+обеспечение\s+ГАРАНТ.*$',
    r'^(?:Система\s+ГАРАНТ|ГАРАНТ\.РУ):?\s.*$',
    r'^См\.\s+(?:предыдущую|будущую)\s+редакцию\.?$',
    r'^Электронный\s+текст\s+документа\s+подготовлен\s.*Кодекс.*$',
    r'^Документ\s+(?:получен|скачан)\s+(?:из|с)\s.*(?:Кодекс|Техэксперт|cntd).*$',
    r'^(?:Позиции\s+высших\s+судов|Путеводитель|Готовое\s+решение|Перспективы\s+и\s+риски|Судебная\s+практика)\b.{0,300}>>>$',
)]

# Блок целиком принадлежит редакционному примечанию системы.
NOTE_BLOCK = re.compile(r'^[\s|\u00a0]*(?:КонсультантПлюс:\s*примечани|ГАРАНТ:\s|Комментарий\s+ГАРАНТа|Информация\s+об\s+изменениях:)', _FLAGS)

# Признаки бренда для итоговой проверки «ничего не осталось».
BRAND_CHECK = re.compile(r'Консультант\s*Плюс|consultant\.ru|ConsultantPlus|блог-инженера|xn--\-[0-9a-z-]*\.xn--p1ai|garant\.ru|Система\s+ГАРАНТ|ГАРАНТ\.РУ|docs\.cntd\.ru', _FLAGS)

# Быстрый предфильтр: без этих слов строка не может содержать служебную надпись.
_TRIGGER = re.compile(r'консультант|consultant|сохранения|страница|гарант|garant|cntd|кодекс|kodeks|techexpert|блог|xn--|>>>|изменениях|редакцию', _FLAGS)

REMOVED_MARK = '[Служебная надпись справочной системы удалена из индекса]'

_SEPARATORS = ' \t |'


def clean_text(text):
    """Вернуть (очищенный_текст, число_удалений). Текст нормы не переписывается."""
    text = str(text)
    if not _TRIGGER.search(text):
        return text, 0
    if NOTE_BLOCK.match(text):
        return '', 1
    removed = 0
    lines = []
    for line in text.split('\n'):
        new = line
        for pattern in INLINE_PATTERNS:
            new, count = pattern.subn('', new)
            removed += count
        stripped = new.strip(_SEPARATORS)
        if new != line:
            if not stripped:
                continue
            # Таблица «ячейка | служебная ячейка»: убрать оставшиеся разделители.
            new = re.sub(r'(?:\s*\|\s*)+$', '', re.sub(r'^(?:\s*\|\s*)+', '', new)).strip(' \t ')
            new = re.sub(r'[ \t ]{2,}', ' ', new)
        if stripped and any(p.match(stripped) for p in LINE_PATTERNS):
            removed += 1
            continue
        lines.append(new)
    return '\n'.join(lines), removed


def contains_brand(text):
    return bool(BRAND_CHECK.search(str(text)))
